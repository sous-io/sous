/**
 * The answer ladder: whether a variable already has an answer, and
 * which environment variable gave it.
 *
 * Five rungs, most specific first:
 *
 * ```text
 * 1. mapping    a record binding any name to this exact variable
 * 2. recipe     SOUS_VAR_<NAMESPACE>_<RECIPE>_<VARIABLE>
 * 3. namespace  SOUS_VAR_<NAMESPACE>_<VARIABLE>
 * 4. shared     SOUS_VAR_<VARIABLE>
 * 5. bare       the definition's own `env` name, or the shared form
 * ```
 *
 * Within a rung the shell environment wins, then `.sous/.env.local`, then `.sous/.env`: the order
 * the env files are loaded in, so what the ladder reports is what a build sees. The three layers
 * are kept apart, so a report can say where an answer came from.
 *
 * Names are generated by `variables.names` and then looked up; nothing parses a name back into
 * its parts, since `_` is both the separator and a legal character.
 */

import type { Environment } from "@sous-io/plugin-api";
import type { EnvFileKind, EnvFileValues } from "@sous-io/plugin-config-files/types";
import type { VariablesNames } from "@sous-io/plugin-variables/types";
import { mappedNamesFor } from "./mappings.js";
import type {
    AnswerDiagnosis,
    AnswerSource,
    AnswerSourceFile,
    DefinedVariable,
    LadderCandidate,
    LadderRung,
    RecipeAnswersLadder,
    ResolvedAnswer,
} from "./types.js";

/** The rungs, most specific first. */
export const LADDER_RUNGS: readonly LadderRung[] = ["mapping", "recipe", "namespace", "shared", "bare"];

/** Each rung in words, for messages. */
export const RUNG_LABELS: Readonly<Record<LadderRung, string>> = {
    mapping: "mapping record",
    recipe: "recipe scope",
    namespace: "namespace scope",
    shared: "shared scope",
    bare: "declared name",
};

/** Each place an answer can come from, in words. */
export const SOURCE_LABELS: Readonly<Record<AnswerSourceFile, string>> = {
    shell: "the shell environment",
    local: "the .env.local file",
    shared: "the .env file",
};

/** The file each env file kind is, by name. */
export const ENV_FILE_NAMES: Readonly<Record<EnvFileKind, string>> = {
    shared: ".env",
    local: ".env.local",
};

/** The three layers the ladder reads, kept apart. */
export interface LadderLayers {
    /** The shell environment, without what the env files added. */
    shell: Record<string, string>;
    /** `.sous/.env.local`. */
    local: Record<string, string>;
    /** `.sous/.env`. */
    shared: Record<string, string>;
}

/**
 * The three layers, from the env files and the engine's environment. A value in the environment
 * equal to the one an env file holds is taken to come from that file, since the env files may have
 * been added to the environment already.
 */
export function layersFrom(files: Pick<EnvFileValues, "shared" | "local"> | undefined, env: Environment): LadderLayers {
    const local = { ...(files?.local ?? {}) };
    const shared = { ...(files?.shared ?? {}) };
    const shell: Record<string, string> = {};

    for (const [name, value] of Object.entries(env)) {
        if (value === undefined || local[name] === value || shared[name] === value) {
            continue;
        }

        shell[name] = value;
    }

    return { shell, local, shared };
}

/** The ladder over one set of layers and mapping records. */
export class Ladder implements RecipeAnswersLadder {
    private readonly layers: LadderLayers;
    private mappingRecords: Record<string, string>;

    /**
     * @param names - Variable names and their spellings (`variables.names`).
     * @param layers - The shell and the two env files.
     * @param mappings - The merged `varMappings` block.
     */
    constructor(
        private readonly names: VariablesNames,
        layers: LadderLayers,
        mappings: Readonly<Record<string, string>> = {},
    ) {
        this.layers = { shell: { ...layers.shell }, local: { ...layers.local }, shared: { ...layers.shared } };
        this.mappingRecords = { ...mappings };
    }

    /** The mapping records the ladder reads. */
    get mappings(): Readonly<Record<string, string>> {
        return this.mappingRecords;
    }

    /** The names set in the two env files. */
    namesInFiles(): Set<string> {
        return new Set([...Object.keys(this.layers.local), ...Object.keys(this.layers.shared)]);
    }

    /**
     * Every name that could answer a variable, most specific first. A name repeated on a later rung
     * is dropped, so a definition whose `env` repeats a generated name is listed once.
     */
    candidates(variable: DefinedVariable): LadderCandidate[] {
        const { namespace, name: recipe } = variable.recipe;
        const name = variable.definition.name;
        const ordered: LadderCandidate[] = [
            ...mappedNamesFor(this.mappingRecords, variable).map((envName) => ({ rung: "mapping" as const, envName })),
            { rung: "recipe", envName: this.names.recipeScopedName(namespace, recipe, name) },
            { rung: "namespace", envName: this.names.namespaceScopedName(namespace, name) },
            { rung: "shared", envName: this.names.sharedName(name) },
            { rung: "bare", envName: this.names.bareName(variable.definition) },
        ];
        const seen = new Set<string>();

        return ordered.filter((candidate) => {
            if (seen.has(candidate.envName)) {
                return false;
            }

            seen.add(candidate.envName);

            return true;
        });
    }

    /** The name a new answer is stored under with nothing else said: the definition's `env`, or its shared name. */
    bareName(variable: DefinedVariable): string {
        return this.names.bareName(variable.definition);
    }

    /** The most specific generated name: `SOUS_VAR_<NAMESPACE>_<RECIPE>_<VARIABLE>`. */
    recipeScopedName(variable: DefinedVariable): string {
        return this.names.recipeScopedName(variable.recipe.namespace, variable.recipe.name, variable.definition.name);
    }

    /** The value one layer holds for a name. */
    lookupIn(file: AnswerSourceFile, envName: string): string | undefined {
        return this.layers[file][envName];
    }

    /** One name, across the three layers in order. */
    lookup(envName: string): { value: string; file: AnswerSourceFile } | undefined {
        for (const file of ["shell", "local", "shared"] as const) {
            const value = this.layers[file][envName];

            if (value !== undefined) {
                return { value, file };
            }
        }

        return undefined;
    }

    resolve(variable: DefinedVariable): ResolvedAnswer | undefined {
        return this.diagnose(variable).resolved;
    }

    diagnose(variable: DefinedVariable): AnswerDiagnosis {
        const candidates = this.candidates(variable);

        for (const candidate of candidates) {
            const hit = this.lookup(candidate.envName);

            if (hit !== undefined) {
                return { resolved: { value: hit.value, source: { ...candidate, file: hit.file } }, candidates };
            }
        }

        return { candidates };
    }

    /** Records a stored value, so later lookups in the same run see it. */
    record(file: AnswerSourceFile, envName: string, value: string): void {
        this.layers[file][envName] = value;
    }

    /** Records a mapping written in this run. */
    addMapping(envName: string, target: string): void {
        this.mappingRecords = { ...this.mappingRecords, [envName]: target };
    }
}

/**
 * Where an answer came from, in one line.
 *
 * ```ts
 * describeSource({ rung: "shared", envName: "SOUS_VAR_API_URL", file: "shared" });
 * // -> "the shared scope name SOUS_VAR_API_URL, from the .env file"
 * ```
 */
export function describeSource(source: AnswerSource): string {
    return `the ${RUNG_LABELS[source.rung]} name ${source.envName}, from ${SOURCE_LABELS[source.file] ?? source.file}`;
}
